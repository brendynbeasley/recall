// Levenshtein distance for typo tolerance
export function levenshtein(a, b) {
  if (a === b) return 0;
  if (!a.length) return b.length; if (!b.length) return a.length;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    prev = cur;
  }
  return prev[b.length];
}
// Compare typed answer against expected: returns {correct, close, distance}
export function gradeAnswer(typed, expected, opts = {}) {
  const t = normalizeAnswer(typed, opts), e = normalizeAnswer(expected, opts);
  if (!e) return { correct: !t, close: false, distance: 0 };
  // accept any of up to 4 alternatives separated by " / ", ";" or ", " (Quizlet behaviour)
  const rawAlts = stripHtml(String(expected ?? '')).split(/\s*(?:\/|;|,)\s*/).map(a => normalizeAnswer(a, opts)).filter(Boolean);
  const alts = opts.allowAlternatives !== false && rawAlts.length > 1 && rawAlts.length <= 4 ? rawAlts : [e];
  for (const alt of [e, ...alts]) {
    if (t === alt) return { correct: true, close: false, distance: 0 };
  }
  let best = Infinity;
  for (const alt of [e, ...alts]) best = Math.min(best, levenshtein(t, alt));
  const tol = opts.typoTolerance === false ? 0 : Math.floor(Math.max(1, e.length) * 0.2);
  if (best <= tol && best <= 3 && e.length > 3) return { correct: true, close: true, distance: best };
  return { correct: false, close: best <= tol + 1, distance: best };
}
// Character diff for showing mistakes (simple LCS-based)
export function diffChars(a, b) {
  const m = a.length, n = b.length;
  const dp = Array.from({ length: m + 1 }, () => new Uint16Array(n + 1));
  for (let i = m - 1; i >= 0; i--) for (let j = n - 1; j >= 0; j--) dp[i][j] = a[i] === b[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
  const out = []; let i = 0, j = 0;
  while (i < m && j < n) {
    if (a[i] === b[j]) { out.push({ t: 'eq', c: a[i] }); i++; j++; }
    else if (dp[i + 1][j] >= dp[i][j + 1]) { out.push({ t: 'del', c: a[i] }); i++; }
    else { out.push({ t: 'ins', c: b[j] }); j++; }
  }
  while (i < m) out.push({ t: 'del', c: a[i++] });
  while (j < n) out.push({ t: 'ins', c: b[j++] });
  return out;
}

